"""Build a style's package files from its tokens.json.

Usage: python3 tools/package.py <name>

Reads <name>/tokens.json, the single source of the style's tokens, and writes next to it:

    tokens.css          CSS custom properties for web dashboards
    <name>.tps          Tableau color palettes (categorical, sequential, diverging); import via Preferences.tps
    powerbi-theme.json  Power BI report theme (data colors, surfaces, text classes)
    DASHBOARD.md        only the YAML front matter between the first two '---' lines is rewritten; the body stays

Run it after every change to tokens.json, so the four files never drift apart.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def css_tokens(t):
    lines = [f"/* {t['name']} — {t['words']['en']} · Vizney Styles {t['number']:02d}",
             f"   Generated from tokens.json by tools/package.py; edit the JSON, not this file. */",
             ":root{"]
    for k, v in t['colors'].items():
        lines.append(f"  --{k}:{v['hex']}; /* {v['role']} */")
    d = t['data']
    for i, c in enumerate(d['categorical'], 1):
        lines.append(f"  --cat-{i}:{c['hex']}; /* {c['name']} */")
    lines.append(f"  --cat-other:{d['other']};")
    lines.append(f"  --comparison:{d['comparison']};")
    for i, c in enumerate(d['sequential'], 1):
        lines.append(f"  --seq-{i}:{c};")
    for i, c in enumerate(d['diverging'], 1):
        lines.append(f"  --div-{i}:{c};")
    ty = t['typography']
    lines.append(f"  --font-sans:'{ty['sans']['en']}',-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;")
    lines.append(f"  --font-serif:'{ty['serif']['en']}',Georgia,'Times New Roman',serif;")
    lines.append(f"  --font-mono:'{ty['mono']['family']}',ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;")
    for k, v in t['radius'].items():
        lines.append(f"  --radius-{k}:{v};")
    for k, v in t['spacing'].items():
        lines.append(f"  --space-{k}:{v};")
    lines.append(f"  --ease:{t['motion']['ease']};")
    lines.append("}")
    lines.append(f"html[lang=\"ko\"]{{--font-sans:'{ty['sans']['ko']} Variable','{ty['sans']['ko']}',-apple-system,BlinkMacSystemFont,'Apple SD Gothic Neo','Malgun Gothic',sans-serif;"
                 f"--font-serif:'{ty['serif']['ko']}','AppleMyungjo','Batang',serif}}")
    return "\n".join(lines) + "\n"


def tableau_tps(t):
    d = t['data']
    name = t['name']

    def palette(title, kind, colors):
        inner = "\n".join(f"      <color>{c}</color>" for c in colors)
        return f'    <color-palette name="{name} — {title}" type="{kind}">\n{inner}\n    </color-palette>'

    cats = [c['hex'] for c in d['categorical']] + [d['other'], d['comparison']]
    body = "\n".join([
        palette("Categorical", "regular", cats),
        palette("Sequential", "ordered-sequential", d['sequential']),
        palette("Diverging", "ordered-diverging", d['diverging']),
    ])
    return ("<?xml version='1.0'?>\n"
            f"<!-- {name} · Vizney Styles {t['number']:02d}. Paste the color-palette elements into My Tableau Repository/Preferences.tps\n"
            "     (inside <preferences>) and restart Tableau Desktop. Generated by tools/package.py from tokens.json. -->\n"
            "<workbook>\n  <preferences>\n" + body + "\n  </preferences>\n</workbook>\n")


def powerbi_theme(t):
    c = {k: v['hex'] for k, v in t['colors'].items()}
    d = t['data']
    font = t['tools']['powerbi']['fontFamily']
    data_colors = [x['hex'] for x in d['categorical']] + [d['other'], c['accent-deep'], d['diverging'][1], d['sequential'][3], d['comparison']]
    text = lambda size, color, family=font: {"fontFace": family, "fontSize": size, "color": color}
    return {
        "name": f"{t['name']} (Vizney Styles {t['number']:02d})",
        "dataColors": data_colors,
        "background": c['canvas'],
        "foreground": c['ink'],
        "tableAccent": c['accent'],
        "good": d['status']['good'],
        "neutral": d['status']['neutral'],
        "bad": d['status']['bad'],
        "maximum": d['sequential'][-1],
        "center": d['sequential'][2],
        "minimum": d['sequential'][0],
        "null": c['hair-2'],
        "textClasses": {
            "callout": text(28, c['ink']),
            "title": text(12, c['ink']),
            "header": text(11, c['text-2']),
            "label": text(10, c['text-2'])
        },
        "visualStyles": {
            "*": {"*": {
                "*": [{"fontFamily": font, "fontSize": 10, "color": {"solid": {"color": c['body']}}}],
                "background": [{"color": {"solid": {"color": c['card']}}, "transparency": 0}],
                "border": [{"show": False}],
                "visualHeader": [{"background": {"solid": {"color": c['card']}}, "foreground": {"solid": {"color": c['text-2']}}}],
                "title": [{"show": True, "fontFamily": font, "fontSize": 12, "fontColor": {"solid": {"color": c['ink']}}, "alignment": "left"}],
                "categoryAxis": [{"gridlineShow": False, "labelColor": {"solid": {"color": c['text-3']}}, "fontSize": 9}],
                "valueAxis": [{"gridlineShow": True, "gridlineColor": {"solid": {"color": c['hair-2']}}, "labelColor": {"solid": {"color": c['text-3']}}, "fontSize": 9}],
                "legend": [{"position": "Top", "fontSize": 9, "labelColor": {"solid": {"color": c['text-2']}}}]
            }},
            "page": {"*": {
                "background": [{"color": {"solid": {"color": c['canvas']}}, "transparency": 0}],
                "outspace": [{"color": {"solid": {"color": c['canvas']}}, "transparency": 0}]
            }}
        },
        "_notes": [
            f"Fonts: install {font} on authoring and viewing machines, or substitute {t['tools']['powerbi']['fallback']}.",
            "Use only the first four dataColors for categories (three hues plus gray Other); the rest are darker fallbacks Power BI needs for long series lists.",
            "Generated by tools/package.py from tokens.json."
        ]
    }


def front_matter(t):
    d, ty = t['data'], t['typography']
    out = ["---",
           f"name: {t['name']}",
           "spec: dashboard.md/0.1",
           "extends: DESIGN.md",
           f"number: {t['number']}",
           f"tagline: {t['words']['en']}",
           f"tagline_ko: {t['words']['ko']}",
           "source: " + ", ".join(t['source']),
           f"sample: {t['sample']['url']}",
           "author: Vizney (https://www.vizney.com)",
           "license: reference only — not an official design; trademarks belong to their owners",
           "colors:"]
    for k, v in t['colors'].items():
        out.append(f"  {k}: \"{v['hex']}\"")
    out.append("data:")
    out.append("  categorical: [" + ", ".join(f"\"{c['hex']}\"" for c in d['categorical']) + "]")
    out.append(f"  other: \"{d['other']}\"")
    out.append(f"  comparison: \"{d['comparison']}\"")
    out.append("  sequential: [" + ", ".join(f"\"{c}\"" for c in d['sequential']) + "]")
    out.append("  diverging: [" + ", ".join(f"\"{c}\"" for c in d['diverging']) + "]")
    out.append(f"  good: \"{d['status']['good']}\"")
    out.append(f"  bad: \"{d['status']['bad']}\"")
    out.append("typography:")
    out.append(f"  serif: {{ en: \"{ty['serif']['en']}\", ko: \"{ty['serif']['ko']}\" }}")
    out.append(f"  sans: {{ en: \"{ty['sans']['en']}\", ko: \"{ty['sans']['ko']}\" }}")
    out.append(f"  mono: \"{ty['mono']['family']}\"")
    out.append("radius: {" + ", ".join(f"{k}: \"{v}\"" for k, v in t['radius'].items()) + "}")
    out.append("spacing: {" + ", ".join(f"{k}: \"{v}\"" for k, v in t['spacing'].items()) + "}")
    out.append("layout: {maxWidth: \"" + t['layout']['maxWidth'] + f"\", columns: {t['layout']['columns']}}}")
    out.append("files: {tokens: tokens.json, css: tokens.css, tableau: " + t['tools']['tableau']['palettes'] + ", powerbi: " + t['tools']['powerbi']['theme'] + ", prompts: prompt.md}")
    out.append("---")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    folder = ROOT / sys.argv[1]
    t = json.loads((folder / 'tokens.json').read_text(encoding='utf-8'))
    (folder / 'tokens.css').write_text(css_tokens(t), encoding='utf-8')
    (folder / f"{t['slug']}.tps").write_text(tableau_tps(t), encoding='utf-8')
    (folder / 'powerbi-theme.json').write_text(json.dumps(powerbi_theme(t), indent=2, ensure_ascii=False) + "\n", encoding='utf-8')
    md = folder / 'DASHBOARD.md'
    body = ""
    if md.exists():
        text = md.read_text(encoding='utf-8')
        if text.startswith('---'):
            end = text.index('\n---', 3)
            body = text[end + 4:].lstrip('\n')
        else:
            body = text
    md.write_text(front_matter(t) + "\n" + body, encoding='utf-8')
    print(f"{t['slug']}: tokens.css, {t['slug']}.tps, powerbi-theme.json, DASHBOARD.md front matter")


if __name__ == '__main__':
    main()
